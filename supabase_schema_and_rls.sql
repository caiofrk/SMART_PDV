-- 1. Create Tables
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    barcode TEXT,
    price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    image_path TEXT,
    category TEXT,
    last_updated TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    total_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    timestamp TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT REFERENCES public.sales(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    product_name TEXT NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1,
    price_at_sale NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sale_items ENABLE ROW LEVEL SECURITY;

-- 3. RLS Policies: Categories
-- Anyone (including customer_app anon users) can view categories
CREATE POLICY "Public categories are viewable by everyone" 
ON public.categories FOR SELECT 
USING (true);

-- Authenticated merchants can insert, update, or delete categories
CREATE POLICY "Authenticated merchants can manage categories" 
ON public.categories FOR ALL 
TO authenticated 
USING (true) 
WITH CHECK (true);

-- 4. RLS Policies: Products
-- Anyone (including customer_app anon users) can view products in the catalog
CREATE POLICY "Public products are viewable by everyone" 
ON public.products FOR SELECT 
USING (true);

-- Authenticated merchants can insert, update, and delete products
CREATE POLICY "Authenticated merchants can manage products" 
ON public.products FOR ALL 
TO authenticated 
USING (true) 
WITH CHECK (true);

-- 5. RLS Policies: Sales & Sale Items
-- Sales records are private: Only authenticated merchants can view and record sales
CREATE POLICY "Authenticated merchants can view sales" 
ON public.sales FOR SELECT 
TO authenticated 
USING (true);

CREATE POLICY "Authenticated merchants can insert sales" 
ON public.sales FOR INSERT 
TO authenticated 
WITH CHECK (true);

CREATE POLICY "Authenticated merchants can view sale items" 
ON public.sale_items FOR SELECT 
TO authenticated 
USING (true);

CREATE POLICY "Authenticated merchants can insert sale items" 
ON public.sale_items FOR INSERT 
TO authenticated 
WITH CHECK (true);

-- 6. Enable Realtime Replication for Products (Customer App Live Showcase)
ALTER PUBLICATION supabase_realtime ADD TABLE public.products;
